@app.get("/api/stats")
def get_stats():
    """Fetches stats from S3 transaction logs"""
    try:
        analyzer = LogAnalyzer(BUCKET_NAME, LOG_KEY)
        analyzer.parse_logs()
        
        if analyzer.df.empty:
            return {"total_transactions": 0, "status_codes": {}, "total_revenue": 0}
            
        total_tx = len(analyzer.df)
        status_counts = analyzer.df['Status'].value_counts().to_dict()
        status_counts_str = {str(k): int(v) for k, v in status_counts.items()}
        
        return {
            "total_transactions": total_tx,
            "status_codes": status_counts_str,
            "total_revenue": int(total_revenue)
        }
    except Exception as e:
        return {"error": str(e)}

