class LogAnalyzer:  

    def __init__(self, bucket_name, log_key):
        self.bucket_name = bucket_name
        self.log_key = log_key
        self.data = []
        self.s3_client = boto3.client('s3', region_name='us-east-1')

    def parse_logs(self):   
        """Parse transaction logs generated by the checkout simulator"""
        # IP - - [Timestamp] "POST /checkout" STATUS AMOUNT GATEWAY LATENCY
        log_pattern = r'(\d+\.\d+\.\d+\.\d+).*?\[(.*?)\].*?"\w+ (.*?)" (\d+) (\d+) ([\w_]+) (\d+)'

        # Retrieve log object from mock S3
        response = self.s3_client.get_object(Bucket=self.bucket_name, Key=self.log_key)
        log_content = response['Body'].read().decode('utf-8')

        self.data = []
        for line in log_content.splitlines():
            if line.startswith('#') or not line.strip():
                continue
            match = re.search(log_pattern, line)
            if match:
                self.data.append({
                    "IP": match.group(1),
                    "Timestamp": match.group(2),
                    "URL": match.group(3),
                    "Status": int(match.group(4)),
                    "Amount": int(match.group(5)),
                    "Gateway": match.group(6),
                    "Latency": int(match.group(7))
                })

        self.df = pd.DataFrame(self.data)

    def security_audit(self):   
        """Flags IPs generating huge volume of transactions rapidly (Fraud Spike)"""
        if self.df.empty:
            return pd.Series(dtype=int)
            
        try:
            self.df['DateTime'] = pd.to_datetime(self.df['Timestamp'], format='%d/%b/%Y:%H:%M:%S')
        except Exception as e:
            return pd.Series(dtype=int)
            
        suspicious_ips = {}
        for ip, group in self.df.groupby('IP'):
            times = group['DateTime'].sort_values().tolist()
            if len(times) < 10:
                continue
            for i in range(9, len(times)):
                time_diff = (times[i] - times[i-9]).total_seconds()
                if time_diff <= 2: # 10 transactions in 2 seconds is fraud
                    suspicious_ips[ip] = len(times)
                    break
        return pd.Series(suspicious_ips, dtype=int)

    def evaluate_healing_routing(self):
        """AI Engine monitors Gateway health and dynamic routing"""
        global active_gateways, degraded_gateways, revenue_saved, total_revenue
        
        if self.df.empty:
            return {"gateway_health": [], "revenue_saved": 0, "total_revenue": 0, "active_gateways": active_gateways}
            
        total_revenue = self.df[self.df['Status'] == 200]['Amount'].sum()
        
        gateway_stats = []
        for gw in ["Razorpay_Core", "Bank_HDFC", "Bank_SBI"]:
            gw_df = self.df[self.df['Gateway'] == gw]
            if gw_df.empty:
                continue
                
            # Look at last 10 transactions for AI window
            recent = gw_df.tail(10)
            success_rate = (len(recent[recent['Status'] == 200]) / len(recent)) * 100
            avg_latency = recent['Latency'].mean()
            
            status = "Healthy"
            if success_rate < 70 or avg_latency > 1000:
                status = "Degraded"
                if gw not in degraded_gateways:
                    degraded_gateways.append(gw)
                    if gw in active_gateways:
                        active_gateways.remove(gw)
                        print(f"[AI AGENT] {gw} degraded! Disabled and routing traffic to backups.")
            elif gw in degraded_gateways and success_rate >= 80 and avg_latency < 800:
                pass
                
            gateway_stats.append({
                "name": gw,
                "success_rate": round(success_rate, 1),
                "latency_ms": int(avg_latency),
                "status": status,
                "is_active": gw in active_gateways
            })
            
        return {
            "gateway_health": gateway_stats,
            "revenue_saved": revenue_saved,
            "total_revenue": int(total_revenue),
            "active_gateways": active_gateways
        }

# Lifespan Context Manager to handle S3 Mock setup & teardown
@asynccontextmanager
async def lifespan(app: FastAPI):
    global mock_env
    mock_env = setup_mock_s3()
    yield
    if mock_env:
        print("[*] Stopping Virtual AWS S3 environment...")
        mock_env.stop()

