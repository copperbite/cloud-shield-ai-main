@app.post("/api/log")
def add_log(payload: dict):
    global revenue_saved
    try:
        log_line = payload.get("log_line")
        ip = payload.get("ip")
        if not log_line or not ip:
            return {"error": "log_line and ip are required"}
            
        analyzer = LogAnalyzer(BUCKET_NAME, LOG_KEY)
        analyzer.parse_logs()
        suspicious = analyzer.security_audit()
        
        if ip in suspicious.index:
            return {"status": "blocked", "message": "Access Denied: AI detected Fraud Spike from your IP!"}
            
        gw = log_line.split(" ")[-2]
        amount = int(log_line.split(" ")[-3])
        status = log_line.split(" ")[-4]
        
        if gw in degraded_gateways and status != "200":
            revenue_saved += amount
            fallback = active_gateways[0] if active_gateways else "Razorpay_Core"
            log_line = log_line.replace(gw, fallback)
            log_line = log_line.replace(f" {status} ", " 200 ")
            
        with open("server.log", "a") as f:
            f.write(log_line + "\n")
            
        s3_client = boto3.client('s3', region_name='us-east-1')
        s3_client.upload_file('server.log', BUCKET_NAME, LOG_KEY)
        
        analyzer.parse_logs()
        new_suspicious = analyzer.security_audit()
        if ip in new_suspicious.index:
            return {"status": "blocked", "message": "Access Denied: AI detected Fraud Spike!"}
            
        return {"status": "success", "message": "Log synced to virtual S3"}
    except Exception as e:
        return {"error": str(e)}

